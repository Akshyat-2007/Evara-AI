import express from 'express';
import pool from '../db/connection.js';

const router = express.Router();

/**
 * GET /api/report/:sessionId
 * Returns the aggregated doctor summary data for an anonymous session.
 */
router.get('/:sessionId', async (req, res, next) => {
  try {
    const { sessionId } = req.params;

    if (!sessionId || typeof sessionId !== 'string') {
      return res.status(400).json({
        error: 'ValidationError',
        message: 'A valid sessionId is required.',
      });
    }

    // 1. Get session info
    const [sessions] = await pool.query(
      'SELECT id, language, created_at FROM sessions WHERE id = ?',
      [sessionId]
    );

    if (sessions.length === 0) {
      return res.status(404).json({
        error: 'NotFound',
        message: 'No session found with the provided identifier.',
      });
    }

    const session = sessions[0];

    // 2. Get messages
    const [messages] = await pool.query(
      'SELECT id, role, content, created_at FROM messages WHERE session_id = ? ORDER BY id ASC',
      [sessionId]
    );

    // 3. Get symptom reports
    const [reports] = await pool.query(
      'SELECT id, symptoms_json, triage_level, suggested_specialist, summary_en, created_at FROM symptom_reports WHERE session_id = ? ORDER BY id ASC',
      [sessionId]
    );

    // 4. Get red flag events
    const [redFlags] = await pool.query(
      'SELECT id, matched_term, created_at FROM red_flag_events WHERE session_id = ? ORDER BY id ASC',
      [sessionId]
    );

    // Aggregate extracted symptoms
    const allSymptoms = [];
    const seenSymptomNames = new Set();

    reports.forEach((report) => {
      let symptoms = [];
      try {
        symptoms = typeof report.symptoms_json === 'string'
          ? JSON.parse(report.symptoms_json)
          : report.symptoms_json || [];
      } catch (e) {
        symptoms = [];
      }

      if (Array.isArray(symptoms)) {
        symptoms.forEach((s) => {
          const key = (s.name || '').toLowerCase().trim();
          if (key && !seenSymptomNames.has(key)) {
            seenSymptomNames.add(key);
            allSymptoms.push(s);
          }
        });
      }
    });

    // Determine highest triage priority: urgent > routine_visit > self_care
    let highestTriage = 'self_care';
    if (redFlags.length > 0) {
      highestTriage = 'urgent';
    } else {
      const levels = reports.map((r) => r.triage_level);
      if (levels.includes('urgent')) highestTriage = 'urgent';
      else if (levels.includes('routine_visit')) highestTriage = 'routine_visit';
    }

    const latestReport = reports.length > 0 ? reports[reports.length - 1] : null;

    // Filter user's verbatim descriptions
    const verbatimPatientInputs = messages
      .filter((m) => m.role === 'user')
      .map((m) => ({
        text: m.content,
        timestamp: m.created_at,
      }));

    res.json({
      sessionId: session.id,
      sessionDate: session.created_at,
      language: session.language,
      totalMessages: messages.length,
      highestTriageLevel: highestTriage,
      suggestedSpecialist: latestReport?.suggested_specialist || 'gynecologist',
      symptoms: allSymptoms,
      clinicalSummaryEn: latestReport?.summary_en || 'Patient initiated PCOS/reproductive health symptom assessment.',
      redFlagEvents: redFlags.map((rf) => ({
        term: rf.matched_term,
        recordedAt: rf.created_at,
      })),
      verbatimPatientInputs,
      messages,
      disclaimer: 'This document is an educational patient-reported summary generated by SakhiGuide to assist clinical discussion. It does not constitute a clinical diagnosis or medical prescription.',
    });
  } catch (err) {
    next(err);
  }
});

export default router;
